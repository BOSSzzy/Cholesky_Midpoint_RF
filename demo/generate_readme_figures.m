%% Generate reproducible scientific figures for README.md
% This script uses the public rf2d APIs and fixed random seeds. Run it from
% any working directory with:
%
%   run("demo/generate_readme_figures.m")

clear; close all; clc;

rootDir = fileparts(fileparts(mfilename("fullpath")));
outputDir = fullfile(rootDir, "docs", "images", "readme");
if ~exist(outputDir, "dir")
    mkdir(outputDir);
end
addpath(rootDir);

%% 1. Normalized covariance kernels
distance = linspace(0, 60, 600);
kernelNames = ["gaussian", "exponential", "spherical", "matern"];
kernelLabels = {"Gaussian", "Exponential", "Spherical", "Matern (nu = 1.5)"};
kernelColors = [0.10 0.35 0.68; 0.84 0.28 0.20; 0.18 0.58 0.38; 0.53 0.31 0.70];
kernelParams = struct("variance", 1.0, "corrLength", [20 20], ...
    "smoothness", 1.5, "nugget", 0.0);

fig = figure("Color", "w", "Visible", "off", "Position", [100 100 1080 650]);
ax = axes(fig);
hold(ax, "on");
for i = 1:numel(kernelNames)
    covariance = rf2d.CovarianceModel.lagged(kernelNames(i), kernelParams, distance, 0);
    plot(ax, distance, covariance / kernelParams.variance, "LineWidth", 2.4, ...
        "Color", kernelColors(i, :));
end
xline(ax, kernelParams.corrLength(1), "--", "Correlation length", ...
    "Color", [0.25 0.25 0.25], "LabelVerticalAlignment", "middle", ...
    "LabelHorizontalAlignment", "left");
grid(ax, "on"); box(ax, "on");
xlabel(ax, "Separation distance, d (m)");
ylabel(ax, "Normalized covariance, rho(d)");
title(ax, "Covariance kernels implemented in rf2d", "FontWeight", "bold");
legend(ax, kernelLabels, "Location", "northeast");
xlim(ax, [distance(1) distance(end)]);
ylim(ax, [0 1.04]);
styleAxes(ax);
exportgraphics(fig, fullfile(outputDir, "covariance-kernels.png"), "Resolution", 200);
close(fig);

%% 2. Matern random-field realization generated by the Cholesky solver
x = linspace(0, 100, 41);
y = linspace(0, 50, 21);
fieldParams = struct("variance", 1.0, "corrLength", [20 8], ...
    "smoothness", 1.5, "nugget", 1e-8);
generator = rf2d.createGenerator(x, y, "matern", fieldParams, ...
    "Solver", "cholesky", "Seed", 202312, "Mean", 0);
field = generator.realize();
[gridX, gridY] = meshgrid(x, y);

fig = figure("Color", "w", "Visible", "off", "Position", [100 100 1560 520]);
layout = tiledlayout(fig, 1, 3, "TileSpacing", "compact", "Padding", "compact");

ax1 = nexttile(layout);
contourf(ax1, x, y, field, 24, "LineColor", "none");
axis(ax1, "tight"); axis(ax1, "equal");
xlabel(ax1, "x (m)"); ylabel(ax1, "y (m)");
title(ax1, "(a) Plan view");
colorbar(ax1);
colormap(ax1, turbo(256));
styleAxes(ax1);

ax2 = nexttile(layout);
surf(ax2, gridX, gridY, field, "EdgeColor", "none");
view(ax2, 36, 30); axis(ax2, "tight");
xlabel(ax2, "x (m)"); ylabel(ax2, "y (m)"); zlabel(ax2, "Standardized value");
title(ax2, "(b) Surface view");
colorbar(ax2);
colormap(ax2, turbo(256));
styleAxes(ax2);

ax3 = nexttile(layout);
histogram(ax3, field(:), 24, "Normalization", "pdf", ...
    "FaceColor", [0.18 0.48 0.72], "FaceAlpha", 0.78, "EdgeColor", "w");
hold(ax3, "on");
z = linspace(min(field(:)), max(field(:)), 300);
normalPdf = exp(-0.5 * z.^2) / sqrt(2 * pi);
plot(ax3, z, normalPdf, "Color", [0.78 0.20 0.16], "LineWidth", 2.2);
xlabel(ax3, "Standardized value"); ylabel(ax3, "Probability density");
title(ax3, "(c) Marginal distribution");
legend(ax3, {"Realization", "N(0,1) reference"}, "Location", "best");
grid(ax3, "on"); box(ax3, "on");
styleAxes(ax3);

title(layout, "Anisotropic Matern random field (Cholesky realization, seed = 202312)", ...
    "FontSize", 15, "FontWeight", "bold");
exportgraphics(fig, fullfile(outputDir, "random-field-realization.png"), "Resolution", 200);
close(fig);

%% 3. Unconditional and observation-conditioned random fields
nx = 41;
ny = 21;
dx = 2.5;
dy = 2.5;
[gridJ, gridK] = meshgrid(1:nx, 1:ny);
gridTable = table((1:numel(gridJ))', gridJ(:), gridK(:), ...
    'VariableNames', {'id', 'j', 'k'});

obsJ = [4; 10; 17; 24; 31; 38; 8; 34];
obsK = [4; 16; 9; 18; 6; 15; 12; 3];
obsValue = [7.8; 11.7; 8.6; 12.1; 9.0; 11.4; 10.9; 8.2];
obsVar = 0.05 * ones(size(obsValue));
observationTable = table(obsJ, obsK, obsValue, obsVar, ...
    'VariableNames', {'j', 'k', 'obsValue', 'obsVar'});

config = struct();
config.grid.dx = dx;
config.grid.dy = dy;
config.covModel.type = "matern";
config.covModel.rangeX = 20.0;
config.covModel.rangeY = 8.0;
config.covModel.smoothness = 1.5;
config.covModel.nugget = 1e-8;
config.prior.mean = 10.0;
config.prior.std = 2.0;
config.sim.nRealizations = 200;
config.sim.randomSeed = 202312;
config.sim.jitter = 1e-10;
config.io.writeOutput = false;
config.logging.enabled = false;

result = rf2d.ConditionalRandomField.fromTables(gridTable, observationTable, config);
unconditional = reshape(result.unconditional.unconditionalField.RF_0001, ny, nx);
conditional = reshape(result.conditional.conditionalField.RF_0001, ny, nx);
conditionalStd = reshape(result.conditional.conditionalStd, ny, nx);
plotX = ((1:nx) - 0.5) * dx;
plotY = ((1:ny) - 0.5) * dy;
obsX = (obsJ - 0.5) * dx;
obsY = (obsK - 0.5) * dy;
sharedLimits = [min([unconditional(:); conditional(:)]), ...
    max([unconditional(:); conditional(:)])];

fig = figure("Color", "w", "Visible", "off", "Position", [100 100 1560 520]);
layout = tiledlayout(fig, 1, 3, "TileSpacing", "compact", "Padding", "compact");

ax1 = nexttile(layout);
contourf(ax1, plotX, plotY, unconditional, 24, "LineColor", "none");
hold(ax1, "on");
scatter(ax1, obsX, obsY, 48, "o", "MarkerFaceColor", "w", ...
    "MarkerEdgeColor", "k", "LineWidth", 1.2);
caxis(ax1, sharedLimits);
axis(ax1, "tight"); axis(ax1, "equal");
xlabel(ax1, "x (m)"); ylabel(ax1, "y (m)");
title(ax1, "(a) Unconditional realization");
colorbar(ax1);
colormap(ax1, turbo(256));
styleAxes(ax1);

ax2 = nexttile(layout);
contourf(ax2, plotX, plotY, conditional, 24, "LineColor", "none");
hold(ax2, "on");
scatter(ax2, obsX, obsY, 58, obsValue, "filled", ...
    "MarkerEdgeColor", "k", "LineWidth", 1.2);
caxis(ax2, sharedLimits);
axis(ax2, "tight"); axis(ax2, "equal");
xlabel(ax2, "x (m)"); ylabel(ax2, "y (m)");
title(ax2, "(b) Conditional realization");
colorbar(ax2);
colormap(ax2, turbo(256));
styleAxes(ax2);

ax3 = nexttile(layout);
contourf(ax3, plotX, plotY, conditionalStd, 24, "LineColor", "none");
hold(ax3, "on");
scatter(ax3, obsX, obsY, 48, "o", "MarkerFaceColor", "w", ...
    "MarkerEdgeColor", "k", "LineWidth", 1.2);
axis(ax3, "tight"); axis(ax3, "equal");
xlabel(ax3, "x (m)"); ylabel(ax3, "y (m)");
title(ax3, "(c) Conditional standard deviation");
colorbar(ax3);
colormap(ax3, turbo(256));
styleAxes(ax3);

exportgraphics(fig, fullfile(outputDir, "conditional-random-field.png"), "Resolution", 200);
close(fig);

fprintf("README figures written to:\n  %s\n", outputDir);

function styleAxes(ax)
ax.FontName = "Arial";
ax.FontSize = 11;
ax.LineWidth = 0.9;
ax.Layer = "top";
end
